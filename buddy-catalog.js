const EmotionEngine = {
    react: (buddyInst, eventType) => {
        if (!buddyInst || !buddyInst.domElement) return;
        const el = buddyInst.domElement;
        let emotion = 'idle';
        switch(eventType) {
            case 'DONE': emotion = 'happy'; break;
            case 'MISSED': emotion = 'sad'; break;
            case 'SNOOZE': emotion = 'focused'; break;
            case 'GOAL': emotion = 'celebrating'; break;
        }

        // Apply advanced physical transformations (Parallax, Lighting, Filters)
        el.style.transition = 'transform 0.6s cubic-bezier(0.34, 1.56, 0.64, 1), filter 0.6s';
        
        // Spawn particle overlays physically over the element
        const spawnParticles = (emoji, count, behavior) => {
            for(let i=0; i<count; i++) {
                const p = document.createElement('div');
                p.textContent = emoji;
                p.style.position = 'absolute';
                p.style.left = (Math.random() * 80 + 10) + '%';
                p.style.top = (Math.random() * 50 + 20) + '%';
                p.style.fontSize = (Math.random() * 15 + 15) + 'px';
                p.style.pointerEvents = 'none';
                p.style.zIndex = '1000';
                p.style.transition = 'all 1.5s ease-out';
                p.style.transform = 'translate(-50%, -50%) scale(0.5)';
                p.style.opacity = '1';
                el.appendChild(p);
                
                requestAnimationFrame(() => {
                    const transY = behavior === 'fall' ? '100px' : '-100px';
                    const rot = Math.random()*60-30;
                    p.style.transform = 'translate(-50%, ' + transY + ') scale(1.5) rotate(' + rot + 'deg)';
                    p.style.opacity = '0';
                });
                setTimeout(() => p.remove(), 1500);
            }
        };

        if (emotion === 'happy') {
            el.style.transform = 'scale(1.1) translateY(-15px)';
            el.style.filter = 'drop-shadow(0 15px 20px rgba(0,255,170,0.4)) brightness(1.2)';
            spawnParticles('✨', 8, 'rise');
        } else if (emotion === 'sad') {
            el.style.transform = 'scale(0.95) translateY(10px)';
            el.style.filter = 'grayscale(0.6) sepia(0.3) brightness(0.8)';
            spawnParticles('💧', 5, 'fall');
        } else if (emotion === 'focused') {
            el.style.transform = 'scale(1.05) perspective(500px) rotateX(10deg)';
            el.style.filter = 'contrast(1.2) drop-shadow(0 0 15px rgba(0, 150, 255, 0.5))';
            spawnParticles('⚡', 3, 'rise');
        } else if (emotion === 'celebrating') {
            el.style.transform = 'scale(1.15) translateY(-20px)';
            el.style.filter = 'drop-shadow(0 20px 30px rgba(255,0,170,0.6)) brightness(1.3) contrast(1.1)';
            spawnParticles('🎉', 12, 'rise');
        }

        setTimeout(() => { 
            if(el) { 
                el.style.transform = 'scale(1.0) translateY(0) rotateX(0)'; 
                el.style.filter = 'none';
            } 
        }, 2000);
    }
};
